-- SciHub · 科研工作台 —— Supabase 建表脚本
-- 幂等：可整段重复执行，不会覆盖已有数据。
--
-- 用法：Supabase Dashboard → SQL Editor → 粘贴本文件 → Run
--
-- 约定：
--   1. 本项目是 SciHub 专用实例，脚本只创建 research_ 前缀的对象；
--      research_ 前缀也让脚本将来被复用到共享项目时，不会与既有表重名。
--   2. 所有表都启用 RLS，策略统一为「只能读写自己名下的行」（auth.uid() = user_id）。
--   3. create policy 不支持 IF NOT EXISTS，因此先 DROP POLICY IF EXISTS 再重建。
--   4. 末尾显式 grant 给 authenticated：即使项目关闭了「Automatically expose new tables」，
--      登录用户仍能通过 Data API 读写（数据行安全由 RLS 保证）。

-- ─────────────────────────────────────────────────────────────
-- 科研记录
-- ─────────────────────────────────────────────────────────────
create table if not exists research_records (
  id          bigint generated by default as identity primary key,
  user_id     uuid not null default auth.uid() references auth.users on delete cascade,
  title       text not null check (length(btrim(title)) > 0),
  category    text not null default '实验日志',
  content     text not null default '',
  tags        text[] not null default '{}',
  occurred_on date not null default current_date,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

alter table research_records enable row level security;

drop policy if exists "own research records" on research_records;
create policy "own research records" on research_records
  for all
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

create index if not exists research_records_user_occurred_idx
  on research_records (user_id, occurred_on desc, created_at desc);

-- 显式授权：即使项目没开「Automatically expose new tables」，登录用户也能经由 Data API 读写。
-- 注意：授权只决定「能否调用 API」，行的可见性仍由上面的 RLS 策略（auth.uid() = user_id）决定。
grant usage on schema public to authenticated;
grant select, insert, update, delete on research_records to authenticated;

-- ─────────────────────────────────────────────────────────────
-- updated_at 自动维护
-- ─────────────────────────────────────────────────────────────
create or replace function research_touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists research_records_touch on research_records;
create trigger research_records_touch
  before update on research_records
  for each row execute function research_touch_updated_at();

-- ─────────────────────────────────────────────────────────────
-- 自检：执行后应看到 tables=1, policies=1, indexes=1, triggers=1
-- ─────────────────────────────────────────────────────────────
select
  (select count(*) from information_schema.tables
     where table_schema = 'public' and table_name = 'research_records')                         as tables,
  (select count(*) from pg_policies
     where schemaname = 'public' and tablename = 'research_records')                            as policies,
  (select count(*) from pg_indexes
     where schemaname = 'public' and indexname = 'research_records_user_occurred_idx')          as indexes,
  (select count(*) from information_schema.triggers
     where trigger_name = 'research_records_touch')                                             as triggers;

-- ─────────────────────────────────────────────────────────────
-- 账号档案：注册登记「用户名 + 电话」，登录支持 邮箱 / 用户名 / 电话 三选一
-- ─────────────────────────────────────────────────────────────
create table if not exists research_profiles (
  user_id    uuid primary key references auth.users on delete cascade,
  username   text not null check (length(btrim(username)) > 0),
  phone      text,
  email      text not null,
  created_at timestamptz not null default now()
);

create unique index if not exists research_profiles_username_idx
  on research_profiles (lower(btrim(username)));
create unique index if not exists research_profiles_email_idx
  on research_profiles (lower(btrim(email)));
create unique index if not exists research_profiles_phone_idx
  on research_profiles (regexp_replace(coalesce(phone, ''), '[^0-9+]', '', 'g'))
  where regexp_replace(coalesce(phone, ''), '[^0-9+]', '', 'g') <> '';

alter table research_profiles enable row level security;

drop policy if exists "own research profile" on research_profiles;
create policy "own research profile" on research_profiles
  for all
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

grant select, insert, update, delete on research_profiles to authenticated;

-- 注册前查重：返回冲突的字段名（username / phone / email），无冲突返回空串。
-- 必须 security definer：注册时用户还没登录，匿名角色读不到 research_profiles。
create or replace function research_check_signup(p_username text, p_phone text, p_email text)
returns text
language sql
security definer
set search_path = public
as $$
  select case
    when exists (
      select 1 from research_profiles
      where lower(btrim(username)) = lower(btrim(coalesce(p_username, '')))
    ) then 'username'
    when btrim(coalesce(p_phone, '')) <> '' and exists (
      select 1 from research_profiles
      where regexp_replace(coalesce(phone, ''), '[^0-9+]', '', 'g')
          = regexp_replace(btrim(p_phone), '[^0-9+]', '', 'g')
    ) then 'phone'
    when exists (
      select 1 from research_profiles
      where lower(btrim(email)) = lower(btrim(coalesce(p_email, '')))
    ) then 'email'
    else ''
  end
$$;

-- 登录标识符 → 邮箱：前端拿到邮箱后再走标准密码登录，不需要邮箱验证码。
create or replace function research_lookup_login_email(p_identifier text)
returns text
language sql
security definer
set search_path = public
as $$
  select email
  from research_profiles
  where lower(btrim(username)) = lower(btrim(coalesce(p_identifier, '')))
     or lower(btrim(email))    = lower(btrim(coalesce(p_identifier, '')))
     or (
       regexp_replace(coalesce(phone, ''), '[^0-9+]', '', 'g') <> ''
       and regexp_replace(coalesce(phone, ''), '[^0-9+]', '', 'g')
         = regexp_replace(btrim(coalesce(p_identifier, '')), '[^0-9+]', '', 'g')
     )
  limit 1
$$;

-- 默认 public 角色即可执行，必须先收回，再只授权给 anon / authenticated。
revoke all on function research_check_signup(text, text, text) from public;
revoke all on function research_lookup_login_email(text) from public;
grant execute on function research_check_signup(text, text, text) to anon, authenticated;
grant execute on function research_lookup_login_email(text) to anon, authenticated;

-- ─────────────────────────────────────────────────────────────
-- 自检 2：账号档案对象。应看到 profile_tables=1, profile_functions=2
-- ─────────────────────────────────────────────────────────────
select
  (select count(*) from information_schema.tables
     where table_schema = 'public' and table_name = 'research_profiles')             as profile_tables,
  (select count(*) from pg_proc p join pg_namespace n on n.oid = p.pronamespace
     where n.nspname = 'public'
       and p.proname in ('research_check_signup', 'research_lookup_login_email'))     as profile_functions;

-- ─────────────────────────────────────────────────────────────
-- 实验方案与方案步骤（从 docx 导入或手动录入）
-- ─────────────────────────────────────────────────────────────
create table if not exists experiment_plans (
  id         bigint generated by default as identity primary key,
  user_id    uuid not null default auth.uid() references auth.users on delete cascade,
  title      text not null check (length(btrim(title)) > 0),
  source     text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table experiment_plans enable row level security;
drop policy if exists "own experiment plans" on experiment_plans;
create policy "own experiment plans" on experiment_plans
  for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
grant select, insert, update, delete on experiment_plans to authenticated;
create index if not exists experiment_plans_user_idx on experiment_plans (user_id, created_at desc);

create table if not exists plan_steps (
  id            bigint generated by default as identity primary key,
  user_id       uuid not null default auth.uid() references auth.users on delete cascade,
  plan_id       bigint not null references experiment_plans on delete cascade,
  position      int not null,
  title         text not null default '',
  instruction   text not null default '',
  fields        jsonb not null default '[]'::jsonb,
  duration_hint text not null default '',
  created_at    timestamptz not null default now(),
  unique (plan_id, position)
);

alter table plan_steps enable row level security;
drop policy if exists "own plan steps" on plan_steps;
create policy "own plan steps" on plan_steps
  for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
grant select, insert, update, delete on plan_steps to authenticated;
create index if not exists plan_steps_plan_idx on plan_steps (plan_id, position);

-- ─────────────────────────────────────────────────────────────
-- 实验执行：一次实验 = 一个 run，status='running' 时可跨天随时继续
-- ─────────────────────────────────────────────────────────────
create table if not exists experiment_runs (
  id           bigint generated by default as identity primary key,
  user_id      uuid not null default auth.uid() references auth.users on delete cascade,
  plan_id      bigint references experiment_plans on delete set null,
  title        text not null default '',
  status       text not null default 'running' check (status in ('running', 'done', 'aborted')),
  current_step int not null default 0,
  started_at   timestamptz not null default now(),
  finished_at  timestamptz,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);

alter table experiment_runs enable row level security;
drop policy if exists "own experiment runs" on experiment_runs;
create policy "own experiment runs" on experiment_runs
  for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
grant select, insert, update, delete on experiment_runs to authenticated;
create index if not exists experiment_runs_user_idx on experiment_runs (user_id, status, updated_at desc);

-- 起跑时把方案步骤"快照"进 run_steps：之后改方案不会篡改历史记录
create table if not exists run_steps (
  id          bigint generated by default as identity primary key,
  user_id     uuid not null default auth.uid() references auth.users on delete cascade,
  run_id      bigint not null references experiment_runs on delete cascade,
  position    int not null,
  title       text not null default '',
  instruction text not null default '',
  fields      jsonb not null default '[]'::jsonb,
  values      jsonb not null default '{}'::jsonb,
  note        text not null default '',
  images      jsonb not null default '[]'::jsonb,
  status      text not null default 'pending' check (status in ('pending', 'done')),
  started_at  timestamptz,
  finished_at timestamptz,
  updated_at  timestamptz not null default now(),
  unique (run_id, position)
);

alter table run_steps enable row level security;
drop policy if exists "own run steps" on run_steps;
create policy "own run steps" on run_steps
  for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
grant select, insert, update, delete on run_steps to authenticated;
create index if not exists run_steps_run_idx on run_steps (run_id, position);

drop trigger if exists experiment_plans_touch on experiment_plans;
create trigger experiment_plans_touch
  before update on experiment_plans
  for each row execute function research_touch_updated_at();

drop trigger if exists experiment_runs_touch on experiment_runs;
create trigger experiment_runs_touch
  before update on experiment_runs
  for each row execute function research_touch_updated_at();

drop trigger if exists run_steps_touch on run_steps;
create trigger run_steps_touch
  before update on run_steps
  for each row execute function research_touch_updated_at();

-- ─────────────────────────────────────────────────────────────
-- 实验照片：私有 bucket；每人只能读写自己 user_id 目录下的文件
-- 路径约定：<user_id>/<run_id>/<step_position>/<文件名>
-- ─────────────────────────────────────────────────────────────
insert into storage.buckets (id, name, public)
values ('experiment-images', 'experiment-images', false)
on conflict (id) do nothing;

drop policy if exists "own experiment images read" on storage.objects;
create policy "own experiment images read" on storage.objects
  for select to authenticated
  using (bucket_id = 'experiment-images' and (storage.foldername(name))[1] = auth.uid()::text);

drop policy if exists "own experiment images write" on storage.objects;
create policy "own experiment images write" on storage.objects
  for insert to authenticated
  with check (bucket_id = 'experiment-images' and (storage.foldername(name))[1] = auth.uid()::text);

drop policy if exists "own experiment images update" on storage.objects;
create policy "own experiment images update" on storage.objects
  for update to authenticated
  using (bucket_id = 'experiment-images' and (storage.foldername(name))[1] = auth.uid()::text);

drop policy if exists "own experiment images delete" on storage.objects;
create policy "own experiment images delete" on storage.objects
  for delete to authenticated
  using (bucket_id = 'experiment-images' and (storage.foldername(name))[1] = auth.uid()::text);

-- ─────────────────────────────────────────────────────────────
-- 自检 3：实验模块。应看到 exp_tables=4, exp_policies=4, exp_bucket=1, exp_image_policies=4
-- ─────────────────────────────────────────────────────────────
select
  (select count(*) from information_schema.tables
     where table_schema = 'public'
       and table_name in ('experiment_plans', 'plan_steps', 'experiment_runs', 'run_steps'))             as exp_tables,
  (select count(*) from pg_policies
     where schemaname = 'public'
       and tablename in ('experiment_plans', 'plan_steps', 'experiment_runs', 'run_steps'))              as exp_policies,
  (select count(*) from storage.buckets where id = 'experiment-images')                                 as exp_bucket,
  (select count(*) from pg_policies
     where schemaname = 'storage' and tablename = 'objects'
       and policyname like 'own experiment images%')                                                    as exp_image_policies;

-- ─────────────────────────────────────────────────────────────
-- 实时同步：把「实验执行」相关表加入 Realtime 发布
-- 同一实验在多台设备上会实时互相推送改动（前端已订阅 run_steps）
-- 幂等：已在发布中则跳过
-- ─────────────────────────────────────────────────────────────
do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'run_steps'
  ) then
    alter publication supabase_realtime add table run_steps;
  end if;

  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'experiment_runs'
  ) then
    alter publication supabase_realtime add table experiment_runs;
  end if;
end
$$;

-- 自检 4：Realtime 发布是否已包含这两张表（预期 realtime_tables=2）
select
  (select count(*) from pg_publication_tables
     where pubname = 'supabase_realtime' and schemaname = 'public'
       and tablename in ('run_steps', 'experiment_runs'))          as realtime_tables;
