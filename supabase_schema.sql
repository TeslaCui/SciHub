-- Create a project and optionally assign all currently unassigned data for the
-- caller. The update is atomic and idempotent by project name. It does not
-- touch rows already assigned to another project.
create or replace function public.research_create_project(
  p_name text, p_migrate_unassigned boolean default false
) returns bigint language plpgsql security invoker set search_path=public as $$
declare v_id bigint;
begin
  if auth.uid() is null then raise exception '请先登录'; end if;
  if nullif(btrim(p_name), '') is null or length(btrim(p_name)) > 120 then
    raise exception '项目名称不能为空且不能超过 120 个字符';
  end if;
  insert into public.research_projects(user_id,name)
    values(auth.uid(), btrim(p_name))
    on conflict (user_id,name) do update set name=excluded.name
    returning id into v_id;
  if p_migrate_unassigned then
    update public.research_records set project_id=v_id
      where user_id=auth.uid() and project_id is null;
    update public.experiment_plans set project_id=v_id
      where user_id=auth.uid() and project_id is null;
    update public.experiment_runs set project_id=v_id
      where user_id=auth.uid() and project_id is null;
  end if;
  return v_id;
end $$;

