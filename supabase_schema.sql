-- 方案实验完成时，把生成的科研日志留在同一项目。
create or replace function public.research_finish_run(p_id bigint,p_content text,p_date date)
returns bigint language plpgsql security invoker set search_path = public as $$
declare v_run public.experiment_runs%rowtype; v_record bigint; v_last integer;
begin
  if auth.uid() is null then raise exception '请先登录'; end if;
  if nullif(btrim(p_content),'') is null then raise exception '日志内容不能为空'; end if;
  select * into v_run from public.experiment_runs where id=p_id and user_id=auth.uid() for update;
  if not found then raise exception '实验不存在或无权操作'; end if;
  if v_run.status='aborted' then raise exception '已终止的实验不能完成'; end if;
  select id into v_record from public.research_records where user_id=auth.uid()
    and tags @> array['experiment:'||p_id::text] order by id limit 1;
  if v_run.status='done' then return v_record; end if;
  select max(position) into v_last from public.run_steps where run_id=p_id and user_id=auth.uid();
  if v_last is null then raise exception '实验没有步骤'; end if;
  if not exists(select 1 from public.run_steps where run_id=p_id and position=v_last and status='done' and user_id=auth.uid()) then
    raise exception '最后一步尚未保存完成';
  end if;
  if v_record is null then
    insert into public.research_records(user_id,project_id,title,category,content,tags,occurred_on)
      values(auth.uid(),v_run.project_id,v_run.title||' · 实验日志','实验日志',p_content,
        array['实验日志','experiment:'||p_id::text],coalesce(p_date,current_date)) returning id into v_record;
  end if;
  update public.experiment_runs set status='done',current_step=v_last,finished_at=now() where id=p_id;
  return v_record;
end $$;
revoke all on function public.research_finish_run(bigint,text,date) from public,anon;
grant execute on function public.research_finish_run(bigint,text,date) to authenticated;
