revoke update on public.experiment_runs from authenticated;
grant update(title,status,current_step,finished_at,updated_at) on public.experiment_runs to authenticated;
revoke insert,update,delete on public.run_steps from authenticated;
grant update(values,note,images,status,started_at,finished_at,checks,link_run_id,link_note) on public.run_steps to authenticated;
revoke all on function public.research_update_step_schema(jsonb),public.research_validate_plan_steps(jsonb) from public,anon;
