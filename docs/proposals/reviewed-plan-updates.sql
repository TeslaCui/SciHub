-- 提案：尚未部署。新增审核、原子提交、采用后续步骤、起跑与私密审计。
-- 不转换旧数据，不重写已有执行快照。须明确授权后复制到新迁移。
create table if not exists public.experiment_plan_update_audits (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  plan_id bigint not null, run_id bigint,
  action text not null check (action in ('save_plan','adopt_tail')),
  before_snapshot jsonb not null, after_snapshot jsonb not null,
  review_snapshot jsonb not null, created_at timestamptz not null default now()
);
alter table public.experiment_plan_update_audits enable row level security;
drop policy if exists "own plan update audits" on public.experiment_plan_update_audits;
create policy "own plan update audits" on public.experiment_plan_update_audits for select using(user_id=auth.uid());
revoke all on public.experiment_plan_update_audits from public,anon,authenticated;
grant select on public.experiment_plan_update_audits to authenticated;
create index if not exists plan_update_audits_owner_plan_idx on public.experiment_plan_update_audits(user_id,plan_id,id desc);

create or replace function public.research_update_step_schema(p_step jsonb)
returns jsonb language sql immutable set search_path=public as $$
  select jsonb_build_object('title',coalesce(p_step->>'title',''),
    'instruction',coalesce(p_step->>'instruction',''),'notice',coalesce(p_step->>'notice',''),
    'pyro_seq',coalesce(p_step->>'pyro_seq',''),'duration_hint',coalesce(p_step->>'duration_hint',''),
    'fields',(select coalesce(jsonb_agg((f-'unit'-'type')||jsonb_build_object('unit',coalesce(f->>'unit',''),'type',coalesce(f->>'type','')) order by ord),'[]')
      from jsonb_array_elements(coalesce(p_step->'fields','[]')) with ordinality x(f,ord)),
    'checklist',(select coalesce(jsonb_agg(item order by item collate "C"),'[]') from (
      select jsonb_array_elements_text(p_step->'checklist') item where p_step ? 'checklist'
      union all select jsonb_object_keys(coalesce(p_step->'checks','{}')) where not (p_step ? 'checklist')
    ) items))
$$;
create or replace function public.research_validate_plan_steps(p_steps jsonb)
returns void language plpgsql immutable set search_path=public as $$
begin
  if p_steps is null or jsonb_typeof(p_steps) is distinct from 'array' then raise exception '步骤格式不合法'; end if;
  if jsonb_array_length(p_steps) not between 1 and 200 then raise exception '步骤数量应为 1 至 200'; end if;
  if exists(select 1 from jsonb_array_elements(p_steps) x(s) where jsonb_typeof(s) is distinct from 'object'
    or nullif(btrim(s->>'title'),'') is null or jsonb_typeof(coalesce(s->'fields','[]')) is distinct from 'array'
    or jsonb_typeof(coalesce(s->'checklist','[]')) is distinct from 'array') then raise exception '步骤或字段格式不合法'; end if;
  if exists(select 1 from jsonb_array_elements(p_steps) x(s),jsonb_array_elements(coalesce(s->'fields','[]')) f(field)
    where jsonb_typeof(field) is distinct from 'object' or nullif(btrim(field->>'label'),'') is null
      or field->>'label' in ('__proto__','constructor','prototype')) then raise exception '字段名称不合法'; end if;
  if exists(select 1 from jsonb_array_elements(p_steps) x(s) where exists(
    select 1 from jsonb_array_elements(coalesce(s->'fields','[]')) f(field) group by btrim(field->>'label') having count(*)>1))
    then raise exception '同一步骤的字段名不可重复'; end if;
end $$;

create or replace function public.research_review_plan_update(p_id bigint,p_steps jsonb,p_run_id bigint default null)
returns jsonb language plpgsql security invoker set search_path=public as $$
declare v_plan public.experiment_plans%rowtype; v_run public.experiment_runs%rowtype;
  v_step public.run_steps%rowtype; v_lock integer; v_issues jsonb:='[]'; v_runs jsonb:='[]'; v_versions jsonb;
begin
  if auth.uid() is null then raise exception '请先登录'; end if;
  perform public.research_validate_plan_steps(p_steps);
  select * into v_plan from public.experiment_plans where id=p_id and user_id=auth.uid();
  if not found then raise exception '方案不存在或无权操作'; end if;
  if p_run_id is not null and not exists(select 1 from public.experiment_runs
    where id=p_run_id and plan_id=p_id and user_id=auth.uid() and status='running') then raise exception '实验不存在、无权操作或已结束'; end if;
  for v_run in select r.* from public.experiment_runs r where r.plan_id=p_id and r.user_id=auth.uid() and r.status='running'
    and (p_run_id is null or r.id=p_run_id)
    and (p_run_id is not null or not exists(select 1 from public.experiment_merge_members m where m.parent_run_id=r.id)) order by r.id loop
    if p_run_id is not null and (exists(select 1 from public.experiment_merge_members where parent_run_id=v_run.id)
      or exists(select 1 from public.experiment_merge_groups where result_run_id=v_run.id)
      or exists(select 1 from public.run_steps where user_id=auth.uid() and (run_id=v_run.id or link_run_id=v_run.id) and link_run_id is not null)) then
      raise exception '合并或旧关联实验保持原快照，不能采用新版后续步骤';
    end if;
    select coalesce(max(position) filter(where status='done'
      or finished_at is not null or btrim(note)<>'' or jsonb_typeof(values)='object' and exists(select 1 from jsonb_each(values) v where nullif(btrim(v.value #>> '{}'),'') is not null) or jsonb_typeof(images)='array' and jsonb_array_length(images)>0
      or exists(select 1 from jsonb_each_text(coalesce(checks,'{}')) c where c.value not in ('false','') and c.value is not null)), -1)
      into v_lock from public.run_steps where run_id=v_run.id and user_id=auth.uid();
    if v_lock>=jsonb_array_length(p_steps) or exists(select 1 from generate_series(0,v_lock) pos
      where not exists(select 1 from public.run_steps where run_id=v_run.id and user_id=auth.uid() and position=pos)) then
      v_issues:=v_issues||jsonb_build_array(jsonb_build_object('run_id',v_run.id,'title',v_run.title,'position',v_lock,'reason','已执行步骤缺失或顺序无法核对'));
    end if;
    for v_step in select * from public.run_steps where run_id=v_run.id and user_id=auth.uid() and position<=v_lock order by position loop
      if public.research_update_step_schema(to_jsonb(v_step)) is distinct from public.research_update_step_schema(p_steps->v_step.position) then
        v_issues:=v_issues||jsonb_build_array(jsonb_build_object('run_id',v_run.id,'title',v_run.title,'position',v_step.position,'reason','已完成、当前或已有记录的步骤定义不一致'));
      end if;
    end loop;
    select coalesce(jsonb_agg(jsonb_build_object('id',id,'position',position,'updated_at',updated_at) order by position),'[]') into v_versions
      from public.run_steps where run_id=v_run.id and user_id=auth.uid();
    v_runs:=v_runs||jsonb_build_array(jsonb_build_object('id',v_run.id,'title',v_run.title,'locked_through',v_lock,'updated_at',v_run.updated_at,'steps',v_versions));
  end loop;
  return jsonb_build_object('allowed',jsonb_array_length(v_issues)=0,'issues',v_issues,'runs',v_runs,
    'plan_id',p_id,'plan_updated_at',v_plan.updated_at,'candidate',(select jsonb_agg(public.research_update_step_schema(s) order by ord) from jsonb_array_elements(p_steps) with ordinality x(s,ord)),'run_id',p_run_id,
    'before_steps',case when p_run_id is null then (select coalesce(jsonb_agg(to_jsonb(s) order by position),'[]') from public.plan_steps s where plan_id=p_id and user_id=auth.uid())
      else (select coalesce(jsonb_agg(to_jsonb(s) order by position),'[]') from public.run_steps s where run_id=p_run_id and user_id=auth.uid()) end);
end $$;

-- 锁定顺序固定：方案 -> 实验 -> 步骤。旧 save RPC 保留签名并同样执行审核。
create or replace function public.research_save_plan(
  p_id bigint,p_title text,p_source text,p_steps jsonb,p_parse_version integer,p_version_log jsonb,p_expected_updated_at timestamptz
) returns bigint language plpgsql security definer set search_path=public as $$
declare v_id bigint; v_plan public.experiment_plans%rowtype; v_review jsonb; v_before jsonb; v_after jsonb;
begin
  if auth.uid() is null then raise exception '请先登录'; end if;
  if nullif(btrim(p_title),'') is null or length(p_title)>200 then raise exception '方案标题不合法'; end if;
  perform public.research_validate_plan_steps(p_steps);
  if jsonb_typeof(coalesce(p_version_log,'[]')) is distinct from 'array' then raise exception '更新日志格式不合法'; end if;
  if p_id is null then
    v_before:=jsonb_build_object('plan',null,'steps','[]'::jsonb);
    v_review:=jsonb_build_object('allowed',true,'runs','[]'::jsonb,'candidate',p_steps);
    insert into public.experiment_plans(user_id,title,source,parse_version,version_log)
      values(auth.uid(),p_title,coalesce(p_source,''),p_parse_version,coalesce(p_version_log,'[]')) returning id into v_id;
  else
    select * into v_plan from public.experiment_plans where id=p_id and user_id=auth.uid() for update;
    if not found then raise exception '方案不存在或无权操作'; end if;
    if exists(select 1 from public.plan_steps where plan_id=p_id and user_id<>auth.uid()) then raise exception '旧方案步骤归属异常，请保留原数据并人工核对'; end if;
    if p_expected_updated_at is null or v_plan.updated_at<>p_expected_updated_at then raise exception '方案已被其他设备修改，请重新打开后核对'; end if;
    perform 1 from public.experiment_runs where plan_id=p_id and user_id=auth.uid() order by id for update;
    perform 1 from public.run_steps where user_id=auth.uid() and run_id in(select id from public.experiment_runs where plan_id=p_id and user_id=auth.uid()) order by run_id,position for update;
    v_review:=public.research_review_plan_update(p_id,p_steps);
    if not (v_review->>'allowed')::boolean then raise exception '更新审核不通过：已完成、当前或已有记录的步骤不匹配'; end if;
    select jsonb_build_object('plan',to_jsonb(v_plan),'steps',coalesce(jsonb_agg(to_jsonb(s) order by s.position),'[]')) into v_before
      from public.plan_steps s where plan_id=p_id and user_id=auth.uid();
    v_id:=p_id;
    update public.experiment_plans set title=p_title,source=coalesce(p_source,''),parse_version=p_parse_version,
      version_log=coalesce(p_version_log,'[]') where id=v_id and user_id=auth.uid();
  end if;
  insert into public.plan_steps(user_id,plan_id,position,title,instruction,fields,duration_hint,notice,pyro_seq,checklist)
    select auth.uid(),v_id,(ord-1)::integer,s->>'title',coalesce(s->>'instruction',''),coalesce(s->'fields','[]'),
      coalesce(s->>'duration_hint',''),coalesce(s->>'notice',''),coalesce(s->>'pyro_seq',''),coalesce(s->'checklist','[]')
    from jsonb_array_elements(p_steps) with ordinality x(s,ord)
    on conflict(plan_id,position) do update set title=excluded.title,instruction=excluded.instruction,fields=excluded.fields,
      duration_hint=excluded.duration_hint,notice=excluded.notice,pyro_seq=excluded.pyro_seq,checklist=excluded.checklist
      where plan_steps.user_id=auth.uid();
  -- 仅移除方案定义中明确超出新长度的尾步；执行记录保留，前后方案完整留在审计中。
  delete from public.plan_steps where plan_id=v_id and user_id=auth.uid() and position>=jsonb_array_length(p_steps);
  select jsonb_build_object('plan',to_jsonb(p),'steps',(select coalesce(jsonb_agg(to_jsonb(s) order by position),'[]') from public.plan_steps s where plan_id=v_id and user_id=auth.uid()))
    into v_after from public.experiment_plans p where id=v_id and user_id=auth.uid();
  insert into public.experiment_plan_update_audits(user_id,plan_id,action,before_snapshot,after_snapshot,review_snapshot)
    values(auth.uid(),v_id,'save_plan',v_before,v_after,v_review||jsonb_build_object('reviewed_by',auth.uid()));
  return v_id;
end $$;
create or replace function public.research_commit_plan_update(
  p_id bigint,p_title text,p_source text,p_steps jsonb,p_parse_version integer,p_version_log jsonb,p_expected_updated_at timestamptz,p_expected_review jsonb
) returns bigint language plpgsql security definer set search_path=public as $$
declare v_review jsonb;
begin
  if auth.uid() is null then raise exception '请先登录'; end if;
  perform 1 from public.experiment_plans where id=p_id and user_id=auth.uid() for update;
  perform 1 from public.experiment_runs where plan_id=p_id and user_id=auth.uid() order by id for update;
  perform 1 from public.run_steps where user_id=auth.uid() and run_id in(select id from public.experiment_runs where plan_id=p_id and user_id=auth.uid()) order by run_id,position for update;
  v_review:=public.research_review_plan_update(p_id,p_steps);
  if p_expected_review is null or v_review<>p_expected_review then raise exception '审核后方案或实验已变化，请重新审核'; end if;
  if not (v_review->>'allowed')::boolean then raise exception '更新审核不通过'; end if;
  return public.research_save_plan(p_id,p_title,p_source,p_steps,p_parse_version,p_version_log,p_expected_updated_at);
end $$;

create or replace function public.research_start_run(p_plan_id bigint,p_expected_updated_at timestamptz)
returns bigint language plpgsql security definer set search_path=public as $$
declare v_plan public.experiment_plans%rowtype; v_id bigint; v_n integer;
begin
  if auth.uid() is null then raise exception '请先登录'; end if;
  select * into v_plan from public.experiment_plans where id=p_plan_id and user_id=auth.uid() for update;
  if not found then raise exception '方案不存在或无权操作'; end if;
  if exists(select 1 from public.plan_steps where plan_id=p_plan_id and user_id<>auth.uid()) then raise exception '旧方案步骤归属异常，请人工核对'; end if;
  if p_expected_updated_at is null or v_plan.updated_at<>p_expected_updated_at then raise exception '方案已变化，请刷新后开始实验'; end if;
  select count(*) into v_n from public.plan_steps where plan_id=p_plan_id and user_id=auth.uid();
  if v_n=0 or exists(select 1 from generate_series(0,v_n-1) pos where not exists(select 1 from public.plan_steps where plan_id=p_plan_id and user_id=auth.uid() and position=pos)) then raise exception '方案没有可用的连续步骤'; end if;
  select count(*)+1 into v_n from public.experiment_runs where plan_id=p_plan_id and user_id=auth.uid();
  insert into public.experiment_runs(user_id,plan_id,title,status,current_step)
    values(auth.uid(),p_plan_id,v_plan.title||case when v_n>1 then '（第 '||v_n||' 次）' else '' end,'running',0) returning id into v_id;
  insert into public.run_steps(user_id,run_id,position,title,instruction,fields,notice,pyro_seq,duration_hint,checks)
    select auth.uid(),v_id,position,title,instruction,fields,notice,pyro_seq,duration_hint,
      (select coalesce(jsonb_object_agg(c,false),'{}') from jsonb_array_elements_text(checklist) x(c))
    from public.plan_steps where plan_id=p_plan_id and user_id=auth.uid() order by position;
  return v_id;
end $$;

create or replace function public.research_adopt_plan_update(p_run_id bigint,p_expected_review jsonb,p_confirm_remove boolean default false)
returns bigint language plpgsql security definer set search_path=public as $$
declare v_run public.experiment_runs%rowtype; v_steps jsonb; v_review jsonb; v_before jsonb; v_after jsonb; v_lock integer;
begin
  if auth.uid() is null then raise exception '请先登录'; end if;
  select * into v_run from public.experiment_runs where id=p_run_id and user_id=auth.uid();
  if not found or v_run.plan_id is null then raise exception '实验不存在或没有可采用的方案'; end if;
  perform 1 from public.experiment_plans where id=v_run.plan_id and user_id=auth.uid() for update;
  select * into v_run from public.experiment_runs where id=p_run_id and user_id=auth.uid() for update;
  perform 1 from public.run_steps where run_id=p_run_id and user_id=auth.uid() order by position for update;
  select coalesce(jsonb_agg(to_jsonb(s) order by position),'[]') into v_steps from public.plan_steps s where plan_id=v_run.plan_id and user_id=auth.uid();
  if exists(select 1 from public.plan_steps where plan_id=v_run.plan_id and user_id<>auth.uid())
    or exists(select 1 from generate_series(0,jsonb_array_length(v_steps)-1) pos where not exists(
      select 1 from public.plan_steps where plan_id=v_run.plan_id and user_id=auth.uid() and position=pos)) then
    raise exception '旧方案步骤归属或顺序异常，请保留原数据并人工核对';
  end if;
  v_review:=public.research_review_plan_update(v_run.plan_id,v_steps,p_run_id);
  if p_expected_review is null or v_review<>p_expected_review then raise exception '审核后方案或实验已变化，请重新审核'; end if;
  if not (v_review->>'allowed')::boolean then raise exception '采用审核不通过：已执行步骤不匹配'; end if;
  v_lock:=(v_review->'runs'->0->>'locked_through')::integer;
  if exists(select 1 from public.run_steps where run_id=p_run_id and user_id=auth.uid() and position>=jsonb_array_length(v_steps)) and not coalesce(p_confirm_remove,false) then
    raise exception '请逐项核对并明确批准移除未开始的尾步';
  end if;
  select jsonb_build_object('run',to_jsonb(v_run),'steps',coalesce(jsonb_agg(to_jsonb(s) order by position),'[]')) into v_before from public.run_steps s where run_id=p_run_id and user_id=auth.uid();
  -- 没有任何数据的未来步骤才可替换；已执行前缀的 ID、值、附件、时间均不写入。
  insert into public.run_steps(user_id,run_id,position,title,instruction,fields,notice,pyro_seq,duration_hint,checks)
    select auth.uid(),p_run_id,position,title,instruction,fields,notice,pyro_seq,duration_hint,
      (select coalesce(jsonb_object_agg(c,false),'{}') from jsonb_array_elements_text(checklist) x(c))
    from public.plan_steps where plan_id=v_run.plan_id and user_id=auth.uid() and position>v_lock order by position
    on conflict(run_id,position) do update set title=excluded.title,instruction=excluded.instruction,fields=excluded.fields,
      notice=excluded.notice,pyro_seq=excluded.pyro_seq,duration_hint=excluded.duration_hint,checks=excluded.checks where run_steps.user_id=auth.uid();
  delete from public.run_steps where run_id=p_run_id and user_id=auth.uid() and position>=jsonb_array_length(v_steps) and position>v_lock;
  update public.experiment_runs set updated_at=now() where id=p_run_id and user_id=auth.uid();
  select jsonb_build_object('run',to_jsonb(r),'steps',(select coalesce(jsonb_agg(to_jsonb(s) order by position),'[]') from public.run_steps s where run_id=p_run_id and user_id=auth.uid())) into v_after
    from public.experiment_runs r where id=p_run_id and user_id=auth.uid();
  insert into public.experiment_plan_update_audits(user_id,plan_id,run_id,action,before_snapshot,after_snapshot,review_snapshot)
    values(auth.uid(),v_run.plan_id,p_run_id,'adopt_tail',v_before,v_after,v_review||jsonb_build_object('reviewed_by',auth.uid(),'confirmed_remove',p_confirm_remove));
  return p_run_id;
end $$;

-- 保留进度、数值、备注、附件、旧关联的普通写入；定义只能由审核 RPC 写入。
