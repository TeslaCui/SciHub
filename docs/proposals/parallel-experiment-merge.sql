-- 用户已明确授权；本提案保留供审阅，实际部署文件在 supabase/migrations/20261008110000_parallel_experiment_merge.sql。
-- 新增两个归属隔离的表、审核/提交 RPC 及防篡改触发器。
-- 不删除、转换旧关联或覆盖既有记录。合并由用户确认时执行。
create table if not exists public.experiment_merge_groups (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id),
  result_run_id bigint not null unique references public.experiment_runs(id),
  after_position integer not null check(after_position >= 0),
  schema_snapshot jsonb not null,
  review_snapshot jsonb not null,
  note text not null default '',
  created_at timestamptz not null default now()
);
create table if not exists public.experiment_merge_members (
  group_id bigint not null references public.experiment_merge_groups(id),
  user_id uuid not null references auth.users(id),
  parent_run_id bigint not null unique references public.experiment_runs(id),
  primary key(group_id,parent_run_id)
);
alter table public.experiment_merge_groups enable row level security;
alter table public.experiment_merge_members enable row level security;
drop policy if exists "own merge groups" on public.experiment_merge_groups;
create policy "own merge groups" on public.experiment_merge_groups for all
  using(user_id=auth.uid()) with check(user_id=auth.uid());
drop policy if exists "own merge members" on public.experiment_merge_members;
create policy "own merge members" on public.experiment_merge_members for all
  using(user_id=auth.uid()) with check(user_id=auth.uid());
revoke all on public.experiment_merge_groups,public.experiment_merge_members from anon,authenticated;
grant select on public.experiment_merge_groups,public.experiment_merge_members to authenticated;
create index if not exists merge_members_group_idx on public.experiment_merge_members(group_id);

create or replace function public.research_merge_normalize(p_text text)
returns text language sql immutable set search_path=public as $$
  select regexp_replace(coalesce(p_text,''),'[[:space:]]+','','g')
$$;
create or replace function public.research_merge_schema(p_run_id bigint)
returns jsonb language sql stable security invoker set search_path=public as $$
  select coalesce(jsonb_agg(jsonb_build_object(
    'position',s.position,'title',research_merge_normalize(s.title),
    'instruction',research_merge_normalize(s.instruction),
    'notice',research_merge_normalize(s.notice),'pyro_seq',research_merge_normalize(s.pyro_seq),
    'duration_hint',research_merge_normalize(s.duration_hint),
    'fields',(select coalesce(jsonb_agg(jsonb_build_object('label',research_merge_normalize(f->>'label'),
      'unit',research_merge_normalize(f->>'unit'),'type',coalesce(f->>'type','text')) order by ord),'[]')
      from jsonb_array_elements(s.fields) with ordinality as fields(f,ord)),
    'checklist',coalesce(to_jsonb(s)->'checklist','[]')
  ) order by s.position),'[]') from public.run_steps s
  where s.run_id=p_run_id and s.user_id=auth.uid()
$$;

create or replace function public.research_review_merge(p_run_ids bigint[],p_after_position integer)
returns jsonb language plpgsql security invoker set search_path=public as $$
declare v_run public.experiment_runs%rowtype; v_id bigint; v_schema jsonb;
  v_reference jsonb; v_count integer; v_versions jsonb:='{}'; v_steps jsonb;
begin
  if auth.uid() is null then raise exception '请先登录'; end if;
  if coalesce(cardinality(p_run_ids),0) not between 2 and 8
    or exists(select 1 from unnest(p_run_ids) x where x is null)
    or (select count(distinct x) from unnest(p_run_ids) x) <> cardinality(p_run_ids) then
    raise exception '请选择 2 至 8 个不同的平行实验';
  end if;
  if p_after_position is null or p_after_position<0 then raise exception '合并边界不合法'; end if;
  foreach v_id in array p_run_ids loop
    select * into v_run from public.experiment_runs where id=v_id and user_id=auth.uid();
    if not found or v_run.status<>'running' then raise exception '实验不存在、无权访问或已结束'; end if;
    if exists(select 1 from public.experiment_merge_members where parent_run_id=v_id)
      or exists(select 1 from public.experiment_merge_groups where result_run_id=v_id) then
      raise exception '实验已属于共同阶段，不能重复或嵌套合并';
    end if;
    if exists(select 1 from public.run_steps where (run_id=v_id or link_run_id=v_id) and link_run_id is not null) then
      raise exception '请先处理旧关联；新合并不会自动转换或覆盖旧关系';
    end if;
    if exists(select 1 from public.run_steps where run_id=v_id and user_id<>auth.uid()) then
      raise exception '实验步骤归属不一致，请先核对数据';
    end if;
    select count(*) into v_count from public.run_steps where run_id=v_id and user_id=auth.uid();
    if v_count<2 or p_after_position>=v_count-1 then raise exception '合并后必须至少保留一个共同步骤'; end if;
    if exists(select 1 from generate_series(0,v_count-1) pos
      where not exists(select 1 from public.run_steps where run_id=v_id and position=pos and user_id=auth.uid())) then
      raise exception '步骤序号不连续，不能安全合并';
    end if;
    v_schema:=public.research_merge_schema(v_id);
    if v_reference is null then v_reference:=v_schema;
    elsif v_reference<>v_schema then
      raise exception '前置或后置步骤不一致：请核对顺序、说明、字段、单位、注意事项、时长和热解条件';
    end if;
    if exists(select 1 from public.run_steps where run_id=v_id and position<=p_after_position and status<>'done') then
      raise exception '每个平行实验都必须先完成合并前的所有步骤';
    end if;
    if exists(select 1 from public.run_steps where run_id=v_id and position>p_after_position
      and (status<>'pending' or values<>'{}'::jsonb or btrim(note)<>'' or images<>'[]'::jsonb
        or finished_at is not null or exists(select 1 from jsonb_each_text(coalesce(checks,'{}')) c where c.value is not null and c.value not in ('false','')))) then
      raise exception '合并后的步骤已有记录；为避免丢失或混淆数据，禁止合并';
    end if;
    select jsonb_agg(jsonb_build_object('id',id,'updated_at',updated_at) order by position)
      into v_steps from public.run_steps where run_id=v_id and user_id=auth.uid();
    v_versions:=v_versions||jsonb_build_object(v_id::text,jsonb_build_object('updated_at',v_run.updated_at,'steps',v_steps));
  end loop;
  return jsonb_build_object('allowed',true,'after_position',p_after_position,
    'schema',v_reference,'versions',v_versions,'run_ids',to_jsonb(p_run_ids));
end $$;

create or replace function public.research_merge_runs(p_run_ids bigint[],p_after_position integer,
  p_note text,p_expected_versions jsonb)
returns bigint language plpgsql security definer set search_path=public as $$
declare v_review jsonb; v_result bigint; v_group bigint; v_id bigint; v_title text;
begin
  if auth.uid() is null then raise exception '请先登录'; end if;
  -- 全部父实验和步骤按固定顺序锁定，审核后输入变化也必须重审。
  if coalesce(cardinality(p_run_ids),0) not between 2 and 8 then raise exception '请选择 2 至 8 个不同的平行实验'; end if;
  perform 1 from public.experiment_runs where id=any(p_run_ids) and user_id=auth.uid() order by id for update;
  perform 1 from public.run_steps where run_id=any(p_run_ids) and user_id=auth.uid() order by run_id,position for update;
  -- 响应丢失后的同一提交重试，返回已有共同阶段，不重复创建。
  select g.result_run_id into v_result from public.experiment_merge_groups g
    where g.user_id=auth.uid() and g.after_position=p_after_position
      and g.review_snapshot->'run_ids'=to_jsonb(p_run_ids)
      and g.review_snapshot->'versions'=p_expected_versions and g.note=btrim(p_note);
  if found then return v_result; end if;
  v_review:=public.research_review_merge(p_run_ids,p_after_position);
  if p_expected_versions is null or v_review->'versions'<>p_expected_versions then
    raise exception '审核后实验数据已变化，请重新审核';
  end if;
  if nullif(btrim(p_note),'') is null or length(p_note)>2000 then raise exception '请填写合并说明（1 至 2000 字）'; end if;
  select title into v_title from public.experiment_runs where id=p_run_ids[1] and user_id=auth.uid();
  insert into public.experiment_runs(user_id,title,status,current_step,plan_id)
    values(auth.uid(),left(v_title,150)||' · '||cardinality(p_run_ids)||' 路共同阶段','running',0,null)
    returning id into v_result;
  insert into public.run_steps(user_id,run_id,position,title,instruction,fields,notice,pyro_seq,duration_hint,checks)
    select auth.uid(),v_result,position-p_after_position-1,title,instruction,fields,notice,pyro_seq,duration_hint,'{}'
    from public.run_steps where run_id=p_run_ids[1] and user_id=auth.uid() and position>p_after_position order by position;
  insert into public.experiment_merge_groups(user_id,result_run_id,after_position,schema_snapshot,review_snapshot,note)
    values(auth.uid(),v_result,p_after_position,v_review->'schema',
      v_review||jsonb_build_object('confirmed_by',auth.uid(),'confirmed_at',now()),btrim(p_note)) returning id into v_group;
  foreach v_id in array p_run_ids loop
    insert into public.experiment_merge_members(group_id,user_id,parent_run_id) values(v_group,auth.uid(),v_id);
  end loop;
  return v_result;
end $$;

-- 触发器以 definer 查询关系，避免通过更改 user_id 或 RLS 视图绕过保护。
create or replace function public.research_guard_merged_step()
returns trigger language plpgsql security definer set search_path=public as $$
declare v_id bigint; v_parent public.experiment_runs%rowtype; v_common boolean;
begin
  v_id:=case when TG_OP='DELETE' then old.run_id else new.run_id end;
  if TG_OP='UPDATE' and (new.run_id<>old.run_id or new.user_id<>old.user_id) then
    raise exception '不能更改执行步骤的实验或账号归属';
  end if;
  select * into v_parent from public.experiment_runs where id=v_id for update;
  if TG_OP<>'DELETE' and (v_parent.id is null or new.user_id<>v_parent.user_id) then raise exception '步骤归属不合法'; end if;
  if exists(select 1 from public.experiment_merge_members where parent_run_id=v_id) then
    raise exception '平行支路已合并，原始记录只读，请进入共同阶段';
  end if;
  select exists(select 1 from public.experiment_merge_groups where result_run_id=v_id) into v_common;
  if v_common then
    if TG_OP<>'UPDATE' or v_parent.status<>'running' then raise exception '共同阶段结构或已完成记录不可修改'; end if;
    if row(new.position,new.title,new.instruction,new.fields,new.notice,new.pyro_seq,new.duration_hint,new.link_run_id,new.link_note)
      is distinct from row(old.position,old.title,old.instruction,old.fields,old.notice,old.pyro_seq,old.duration_hint,old.link_run_id,old.link_note) then
      raise exception '共同阶段步骤定义已经锁定';
    end if;
  end if;
  if TG_OP='DELETE' then return old; end if;
  return new;
end $$;
create or replace function public.research_guard_merged_run()
returns trigger language plpgsql security definer set search_path=public as $$
declare v_common boolean;
begin
  if exists(select 1 from public.experiment_merge_members where parent_run_id=old.id) then
    raise exception '已合并的平行支路不可修改或删除';
  end if;
  select exists(select 1 from public.experiment_merge_groups where result_run_id=old.id) into v_common;
  if v_common then
    if TG_OP='DELETE' then raise exception '合并链路需保留，不能直接删除共同阶段'; end if;
    if old.status<>'running' or new.user_id<>old.user_id or new.plan_id is distinct from old.plan_id then
      raise exception '共同阶段归属或已完成记录不可修改';
    end if;
    if new.status='done' and exists(select 1 from public.run_steps where run_id=old.id and status<>'done') then
      raise exception '共同阶段的所有步骤必须完成后才能结束';
    end if;
  end if;
  return new;
end $$;
drop trigger if exists run_steps_merge_guard on public.run_steps;
create trigger run_steps_merge_guard before insert or update or delete on public.run_steps
  for each row execute function public.research_guard_merged_step();
drop trigger if exists experiment_runs_merge_guard on public.experiment_runs;
create trigger experiment_runs_merge_guard before update or delete on public.experiment_runs
  for each row execute function public.research_guard_merged_run();

revoke all on function public.research_merge_normalize(text),public.research_merge_schema(bigint),
  public.research_review_merge(bigint[],integer),public.research_merge_runs(bigint[],integer,text,jsonb),
  public.research_guard_merged_step(),public.research_guard_merged_run() from public,anon;
grant execute on function public.research_merge_normalize(text),public.research_merge_schema(bigint),
  public.research_review_merge(bigint[],integer),public.research_merge_runs(bigint[],integer,text,jsonb) to authenticated;
