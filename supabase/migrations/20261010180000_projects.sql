-- v1.2.3: project workspaces.
-- This migration is additive. Existing rows keep project_id = null until the
-- user chooses a project. Deleting a project only unassigns rows; it never
-- deletes plans, runs, records, steps, values, or attachments.

create table if not exists public.research_projects (
  id         bigint generated by default as identity primary key,
  user_id    uuid not null default auth.uid() references auth.users(id) on delete cascade,
  name       text not null check (length(btrim(name)) between 1 and 120),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, name)
);

alter table public.research_projects enable row level security;
drop policy if exists "own research projects" on public.research_projects;
create policy "own research projects" on public.research_projects
  for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
grant select, insert, update, delete on public.research_projects to authenticated;
create index if not exists research_projects_user_idx
  on public.research_projects(user_id, updated_at desc, created_at desc);

drop trigger if exists research_projects_touch on public.research_projects;
create trigger research_projects_touch
  before update on public.research_projects
  for each row execute function public.research_touch_updated_at();

alter table public.research_records
  add column if not exists project_id bigint references public.research_projects(id) on delete set null;
alter table public.experiment_plans
  add column if not exists project_id bigint references public.research_projects(id) on delete set null;
alter table public.experiment_runs
  add column if not exists project_id bigint references public.research_projects(id) on delete set null;

create index if not exists research_records_project_idx
  on public.research_records(user_id, project_id, occurred_on desc, created_at desc);
create index if not exists experiment_plans_project_idx
  on public.experiment_plans(user_id, project_id, updated_at desc);
create index if not exists experiment_runs_project_idx
  on public.experiment_runs(user_id, project_id, status, updated_at desc);

-- Keep the existing account boundary and add a second boundary for project_id.
drop policy if exists "own research records" on public.research_records;
create policy "own research records" on public.research_records
  for all using (auth.uid() = user_id)
  with check (auth.uid() = user_id and
    (project_id is null or exists(select 1 from public.research_projects p
      where p.id = project_id and p.user_id = auth.uid())));
drop policy if exists "own experiment plans" on public.experiment_plans;
create policy "own experiment plans" on public.experiment_plans
  for all using (auth.uid() = user_id)
  with check (auth.uid() = user_id and
    (project_id is null or exists(select 1 from public.research_projects p
      where p.id = project_id and p.user_id = auth.uid())));
drop policy if exists "own experiment runs" on public.experiment_runs;
create policy "own experiment runs" on public.experiment_runs
  for all using (auth.uid() = user_id)
  with check (auth.uid() = user_id and
    (project_id is null or exists(select 1 from public.research_projects p
      where p.id = project_id and p.user_id = auth.uid())));

-- Create a project and optionally assign all currently unassigned data for the
-- caller. The update is atomic and idempotent by project name. It does not
-- touch rows already assigned to another project.
create or replace function public.research_create_project(
  p_name text, p_migrate_unassigned boolean default false
) returns bigint language plpgsql security invoker set search_path=public as $$
declare v_id bigint;
begin
  if auth.uid() is null then raise exception '请先登录'; end if;
  if nullif(btrim(p_name), '') is null or length(btrim(p_name)) > 120 then
    raise exception '项目名称不能为空且不能超过 120 个字符';
  end if;
  insert into public.research_projects(user_id,name)
    values(auth.uid(), btrim(p_name))
    on conflict (user_id,name) do update set name=excluded.name
    returning id into v_id;
  if p_migrate_unassigned then
    update public.research_records set project_id=v_id
      where user_id=auth.uid() and project_id is null;
    update public.experiment_plans set project_id=v_id
      where user_id=auth.uid() and project_id is null;
    update public.experiment_runs set project_id=v_id
      where user_id=auth.uid() and project_id is null;
  end if;
  return v_id;
end $$;

revoke all on function public.research_create_project(text,boolean) from public, anon;
grant execute on function public.research_create_project(text,boolean) to authenticated;

-- Keep completed experiment logs in the same project as their run.
create or replace function public.research_finish_run(p_id bigint,p_content text,p_date date)
returns bigint language plpgsql security invoker set search_path = public as $$
declare v_run public.experiment_runs%rowtype; v_record bigint; v_last integer;
begin
  if auth.uid() is null then raise exception '请先登录'; end if;
  if nullif(btrim(p_content),'') is null then raise exception '日志内容不能为空'; end if;
  select * into v_run from public.experiment_runs where id=p_id and user_id=auth.uid() for update;
  if not found then raise exception '实验不存在或无权操作'; end if;
  if v_run.status='aborted' then raise exception '已终止的实验不能完成'; end if;
  select id into v_record from public.research_records where user_id=auth.uid()
    and tags @> array['experiment:'||p_id::text] order by id limit 1;
  if v_run.status='done' then return v_record; end if;
  select max(position) into v_last from public.run_steps where run_id=p_id and user_id=auth.uid();
  if v_last is null then raise exception '实验没有步骤'; end if;
  if not exists(select 1 from public.run_steps where run_id=p_id and position=v_last and status='done' and user_id=auth.uid()) then
    raise exception '最后一步尚未保存完成';
  end if;
  if v_record is null then
    insert into public.research_records(user_id,project_id,title,category,content,tags,occurred_on)
      values(auth.uid(),v_run.project_id,v_run.title||' · 实验日志','实验日志',p_content,
        array['实验日志','experiment:'||p_id::text],coalesce(p_date,current_date)) returning id into v_record;
  end if;
  update public.experiment_runs set status='done',current_step=v_last,finished_at=now() where id=p_id;
  return v_record;
end $$;

revoke all on function public.research_finish_run(bigint,text,date) from public,anon;
grant execute on function public.research_finish_run(bigint,text,date) to authenticated;
