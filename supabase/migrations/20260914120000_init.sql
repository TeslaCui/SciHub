-- ─────────────────────────────────────────────────────────────
-- updated_at 自动维护
-- ─────────────────────────────────────────────────────────────
create or replace function research_touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists research_records_touch on research_records;
create trigger research_records_touch
  before update on research_records
  for each row execute function research_touch_updated_at();

